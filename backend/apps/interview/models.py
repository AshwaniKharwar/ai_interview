import enum
import uuid
from datetime import datetime
from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, Text, Uuid, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import JSON

from core.database import Base


# JSON type supporting both SQLite in tests and native JSONB in PostgreSQL
JSON_TYPE = JSON().with_variant(JSONB, "postgresql")


class InterviewStatus(str, enum.Enum):
    DRAFT = "DRAFT"
    PARSING = "PARSING"
    BLUEPRINT_GENERATING = "BLUEPRINT_GENERATING"
    BLUEPRINT_READY = "BLUEPRINT_READY"
    FAILED_EXTRACTION = "FAILED_EXTRACTION"
    FAILED_GENERATION = "FAILED_GENERATION"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    EVALUATED = "EVALUATED"


class InterviewSession(Base):
    __tablename__ = "interview_sessions"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )

    # Target Job Details
    job_title: Mapped[str] = mapped_column(String(255), nullable=False)
    company_name: Mapped[str | None] = mapped_column(String(255), nullable=True)
    job_description_raw: Mapped[str] = mapped_column(Text, nullable=False)
    parsed_jd_json: Mapped[dict | None] = mapped_column(JSON_TYPE, nullable=True)

    # Candidate Resume & Parsed Data
    resume_file_url: Mapped[str | None] = mapped_column(String(1024), nullable=True)
    resume_raw_text: Mapped[str | None] = mapped_column(Text, nullable=True)
    parsed_resume_json: Mapped[dict | None] = mapped_column(JSON_TYPE, nullable=True)

    # Gap Analysis
    gap_analysis_json: Mapped[dict | None] = mapped_column(JSON_TYPE, nullable=True)

    # Interview Configuration
    duration_minutes: Mapped[int] = mapped_column(Integer, default=30, nullable=False)
    difficulty_level: Mapped[str] = mapped_column(String(50), default="medium", nullable=False)
    interviewer_persona: Mapped[str] = mapped_column(
        String(50), default="rigorous_collaborative", nullable=False
    )

    # Blueprint generated by LLM
    blueprint_json: Mapped[dict | None] = mapped_column(JSON_TYPE, nullable=True)

    # Model Observability & Error Tracking
    llm_model_used: Mapped[str | None] = mapped_column(String(100), nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Session Status Lifecycle
    status: Mapped[str] = mapped_column(
        String(50),
        default=InterviewStatus.DRAFT.value,
        index=True,
        nullable=False,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    # Relationships
    turns: Mapped[list["InterviewTurn"]] = relationship(
        "InterviewTurn",
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="InterviewTurn.turn_index",
        lazy="selectin",
    )

    def __repr__(self) -> str:
        return f"<InterviewSession id={self.id} job_title={self.job_title} status={self.status}>"


class InterviewTurn(Base):
    __tablename__ = "interview_turns"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )
    session_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("interview_sessions.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    turn_index: Mapped[int] = mapped_column(Integer, nullable=False)

    stage_id: Mapped[str] = mapped_column(String(100), nullable=False)
    question_text: Mapped[str] = mapped_column(Text, nullable=False)
    answer_transcript: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Timing & Performance Telemetry
    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    ended_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    latency_ms: Mapped[int | None] = mapped_column(Integer, nullable=True)
    was_interrupted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # Phase 4 Hook: Structured evaluation of this specific turn
    turn_evaluation_json: Mapped[dict | None] = mapped_column(JSON_TYPE, nullable=True)

    # Relationships
    session: Mapped["InterviewSession"] = relationship("InterviewSession", back_populates="turns")

    def __repr__(self) -> str:
        return f"<InterviewTurn id={self.id} session_id={self.session_id} turn={self.turn_index} stage={self.stage_id}>"

